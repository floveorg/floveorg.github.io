#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Export source-owned vocabulary snapshots into standards/vocabulary.html.

The page must work on file://, where fetch() is blocked. This tool exports the
pieces it needs from their canonical owners into a marked JS block:

  - the Development workflow schemas chapter (schemas.md);
  - the §13.7 prefix table (vocabulary.md);
  - field names from milestones.json and common.json, PROC fields from
    development/AGENTS.md, schema ids from schemas.md;
  - workflow taxonomy families and values (sections, stages, synonyms, tasks,
    archive, states, evidence, impact, procedures and queue policy);
  - the development/addons folder tree (depth 2).

`--check` is the gate (no writes); `--build` regenerates the marked block.
The page never becomes a second owner: every value here has a path back to source.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
PAGE = os.path.join(ROOT, "development", "standards", "vocabulary.html")
BEGIN = "// BEGIN VOCAB SNAPSHOT — generated by tools/dev/checks/check-vocab-snapshot.py"
END = "// END VOCAB SNAPSHOT"
FIELD_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
        return fh.read()


def load_json(path):
    return json.loads(read(path))


def field_keys(node, found):
    """Collect canonical field names, skipping dynamic id-maps (task ids)."""
    if isinstance(node, dict):
        for key, value in node.items():
            if FIELD_RE.fullmatch(key):
                found.add(key)
            field_keys(value, found)
    elif isinstance(node, list):
        for value in node:
            field_keys(value, found)


def json_fields(path):
    found = set()
    field_keys(load_json(path), found)
    return sorted(found)


def proc_fields():
    found = ["id", "title"]
    for match in re.finditer(r"^- ([A-Za-z][A-Za-z ]+):", read("development/AGENTS.md"), re.M):
        field = match.group(1).strip().lower().replace(" ", "_")
        if field not in found:
            found.append(field)
    return found


def schemas_snapshot():
    text = read("development/standards/data/schemas/schemas.md")
    start = text.index('<a id="development-workflow-schemas">')
    end = text.index("\n## Work", start)
    return text[start:end].rstrip() + "\n"


def schema_ids():
    text = schemas_snapshot()
    return list(dict.fromkeys(re.findall(r"`(flove-[a-z0-9-]+/\d+)`", text)))


def vocab_prefixes():
    found, seen = [], set()
    for line in read("development/standards/vocabulary.md").splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2:
            continue
        concept = re.sub(r"\s+", " ", cells[1].replace("`", "")).strip()
        for token in re.findall(r"`([^`]+)`", cells[0]):
            key = token.replace("*", "").strip()
            if key and key not in seen:
                seen.add(key)
                found.append({"term": key, "meaning": concept})
    return found


def agents_row(topic):
    """Return the rule cell of one row in the AGENTS.md reading-notes table."""
    for line in read("development/AGENTS.md").splitlines():
        if not line.startswith("|") or topic not in line.split("|")[1]:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) > 1:
            return cells[1]
    return ""


def vocab_groups():
    return [
        {"source": "development/tasks/milestones.json", "terms": json_fields("development/tasks/milestones.json")},
        {"source": "development/tasks/common.json", "terms": json_fields("development/tasks/common.json")},
        {"source": "development/AGENTS.md#2-procedures", "terms": proc_fields()},
        {"source": "development/standards/data/schemas/schemas.md#development-workflow-schemas", "terms": schema_ids()},
        {"source": "development/standards/vocabulary.md#137-canonical-vocabulary", "terms": [x["term"] for x in vocab_prefixes()]},
    ]


def dev_taxonomies():
    """Workflow naming taxonomies, grouped by the shared 1–5 depth ladder.

    Depth 1 lists the families themselves; depths 2–5 list their canonical
    values, machine names, data views and contracts. Every row points back to
    the file that owns it, so vocabulary.html stays a projection, not an owner.
    """
    out = []
    def add(depth, family, term, source, note=""):
        out.append({"depth": depth, "family": family, "term": term,
                    "source": source, "note": note})

    milestones = load_json("development/tasks/milestones.json")
    common = load_json("development/tasks/common.json")
    agents = read("development/AGENTS.md")

    sections = sorted(set(re.findall(r'"section":\s*"([^"]+)"', read("development/tasks/milestones.json"))))
    stages = list(dict.fromkeys(common.get("stageNames", [])))
    effort_row = agents_row("Effort ladder")
    efforts = list(dict.fromkeys(x for x in re.findall(r"`([^`]+)`", effort_row)
                                 if x in {"easiest", "easy", "medium", "hard", "hardest"}))[:5]
    axes_row = agents_row("Axes")
    synonyms = []
    left = axes_row.split(" are display synonyms for ", 1)
    if len(left) == 2:
        axis = (re.findall(r"`([^`]+)`", left[1]) or ["effort"])[0]
        # Only the clause immediately before "are display synonyms for" names
        # the synonyms; the earlier clauses define the two canonical axes.
        clause = left[0].rsplit(".", 1)[-1]
        synonyms += [(term, axis) for term in re.findall(r"`([^`]+)`", clause)]
    pair = re.search(r"`([^`]+)`\s*/\s*`([^`]+)`\s*for\s*`([^`]+)`", axes_row)
    if pair:
        synonyms += [(pair.group(1), pair.group(3)), (pair.group(2), pair.group(3))]
    impact_row = agents_row("Impact")
    impacts = list(dict.fromkeys(x for x in re.findall(r"`([^`]+)`", impact_row)
                                 if x in {"direct", "simple", "branched", "complex", "structuring"}))
    evidence_row = agents_row("Evidence")
    evidence = [x for x in re.findall(r"`([^`]+)`", evidence_row)
                if x in {"command", "anchor", "state"}]
    states_found = set()
    def collect_states(node):
        if isinstance(node, dict):
            for key, value in node.items():
                if key == "state" and isinstance(value, str):
                    states_found.add(value)
                collect_states(value)
        elif isinstance(node, list):
            for value in node:
                collect_states(value)
    collect_states(milestones)
    collect_states(common)
    states = sorted(states_found)
    reasons = milestones.get("taskSet", {}).get("archive_reasons", {})
    procedures = common.get("procedures", [])
    task_fields = sorted({key for task in common.get("tasks", {}).values()
                          for key in task if FIELD_RE.fullmatch(key)})
    queue = common.get("queuePolicy", {})

    families = [
        ("sections", len(sections), "development/tasks/milestones.json", "canonical section labels"),
        ("stages", len(stages), "development/AGENTS.md", "hito maturity axis"),
        ("effort", len(efforts), "development/AGENTS.md", "task difficulty axis"),
        ("synonyms", len(synonyms), "development/AGENTS.md", "display-only names, never fields"),
        ("tasks", len(task_fields), "development/tasks/common.json", "spec fields on every live task"),
        ("states", len(states), "development/tasks/common.json", "task state vocabulary"),
        ("archive", len(reasons), "development/tasks/milestones.json", "reason codes for archived tasks"),
        ("evidence", len(evidence), "development/AGENTS.md", "evidence pointer kinds"),
        ("impact", len(impacts), "development/AGENTS.md", "advisory question-depth classes"),
        ("procedures", len(procedures), "development/AGENTS.md", "canonical PROC ids"),
        ("queue policy", len(queue), "development/tasks/common.json", "queue numbers source"),
    ]
    for family, count, source, note in families:
        add(1, "taxonomies", family, source, "%d canonical values · %s" % (count, note))

    for term in stages: add(2, "stages", term, "development/AGENTS.md", "stage")
    for term in efforts: add(2, "effort", term, "development/AGENTS.md", "effort")
    for term, axis in synonyms:
        add(2, "synonyms", term, "development/AGENTS.md", "display synonym for " + axis)
    for term in states: add(2, "states", term, "development/tasks/common.json", "task state")
    for term, note in reasons.items():
        add(2, "archive", term, "development/tasks/milestones.json", note)
    for term in evidence: add(2, "evidence", term, "development/AGENTS.md", "evidence kind")
    for term in impacts: add(2, "impact", term, "development/AGENTS.md", "question depth")
    for proc in procedures:
        add(2, "procedures", proc.get("id", ""), "development/AGENTS.md", proc.get("title", ""))
    for term, value in queue.items():
        add(2, "queue policy", term, "development/tasks/common.json", str(value))

    for group in vocab_groups():
        # Schema ids are contracts (Depth 5), not machine names (Depth 3).
        if "schemas.md" in group["source"]:
            continue
        for term in group["terms"]:
            family = "prefixes" if "vocabulary.md" in group["source"] else "field names"
            add(3, family, term, group["source"], "machine name")

    data_views = [
        ("Development", "development/index.html", "Apps tree and task data"),
        ("App types mirror", "development/standards/frontend/apps/apps.md", "Frontend app types"),
        ("Pages manifest", "development/pages.json", "live page and redirect map"),
        ("Port ledger", "development/port-ledger.json", "routed app anchors"),
        ("Register inventory", "development/register-path-inventory.json", "path audit of the register"),
        ("Archive manifests", "development/archive/manifest.json", "opaque checksummed snapshots"),
    ]
    for term, path, note in data_views:
        add(4, "derived views", term, path, note)

    for schema in schema_ids():
        add(5, "schema ids", schema, "development/standards/data/schemas/schemas.md", "envelope contract")
    chapter = schemas_snapshot().split("### Layer 3 · auditors and checkers", 1)[-1]
    for line in chapter.splitlines():
        cells = [c.strip() for c in line.split("|")]
        if len(cells) < 5 or not cells[1].startswith("`tools/dev/checks/"):
            continue
        add(5, "auditors", cells[1].strip("`"), "development/standards/data/schemas/schemas.md",
            "%s — %s" % (cells[2].replace("`", ""), cells[3].replace("`", "")))
    return out


def addon_dirs():
    base = os.path.join(ROOT, "development", "addons")
    out = []
    for root, dirs, files in os.walk(base):
        dirs.sort()
        depth = os.path.relpath(root, base).count(os.sep) + (1 if os.path.relpath(root, base) != "." else 0)
        if depth >= 2:
            dirs.clear()
            continue
        for name in dirs:
            out.append(os.path.relpath(os.path.join(root, name), ROOT).replace(os.sep, "/"))
    return sorted(out)


def build_payload():
    return {
        "canonical": {
            "schemas": schemas_snapshot(),
            "vocab-model": "# flove · Canonical vocabulary — §13.7\n\n"
            + "\n".join(f"- `{x['term']}` — {x['meaning']}" for x in vocab_prefixes())
            + "\n",
        },
        "vocab": vocab_groups(),
        "taxonomies": dev_taxonomies(),
        "addons": addon_dirs(),
    }


def render_block(payload):
    lines = [BEGIN]
    for name, value in (("CANONICAL_SNAPSHOT", payload["canonical"]),
                        ("WORKFLOW_VOCAB", payload["vocab"]),
                        ("DEV_TAXONOMIES", payload["taxonomies"]),
                        ("ADDON_DIRS", payload["addons"])):
        encoded = json.dumps(value, ensure_ascii=False, indent=2)
        # Escaped angle brackets keep literal markup inside source snapshots from
        # being parsed as page markup (and from tripping HTML/a11y scanners).
        encoded = encoded.replace("<", "\\u003c").replace(">", "\\u003e")
        lines.append("const %s = %s;" % (name, encoded))
    lines.append(END)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--build", action="store_true", help="rewrite the marked block in vocabulary.html")
    ap.add_argument("--check", action="store_true", help="verify the marked block (default)")
    args = ap.parse_args()
    page = Path(PAGE).read_text(encoding="utf-8")
    if page.count(BEGIN) != 1 or page.count(END) != 1:
        print("FAIL: vocabulary.html must hold exactly one vocab snapshot block")
        return 1
    before, rest = page.split(BEGIN, 1)
    old_block, after = rest.split(END, 1)
    old_block = BEGIN + old_block + END
    new_block = render_block(build_payload())
    if args.build:
        Path(PAGE).write_text(before + new_block + after, encoding="utf-8")
        print("vocab snapshot rebuilt: %s" % os.path.relpath(PAGE, ROOT))
        return 0
    if old_block != new_block:
        print("FAIL: vocab snapshot drift — regenerate with --build")
        return 1
    print("OK: vocab snapshot matches canonical sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
