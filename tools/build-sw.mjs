#!/usr/bin/env node
// build-sw.mjs — regenerates sw.js, the flove service worker.
//
// Full-offline PWA: the worker is registered at the site/package ROOT (/sw.js)
// so its scope is "/" and it can precache the home, every app, the shared images
// (central/shared/media/images) and the tools entry. Source of truth = the
// tracked tree (`git ls-files`), so the precache list always matches what
// flove.org serves and what the download ships. Run before publishing (and from
// build-flove-zip.sh) whenever site files change, then commit sw.js.
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SELF = dirname(fileURLToPath(import.meta.url));   // tools/
const REPO = join(SELF, '..');                          // repo root = site root
const ROOT = REPO;                                      // sw.js lives at the root

// Runtime asset types worth caching for offline. (No .sh/.mjs/.md/dev config.)
const ALLOW = new Set([
  'html', 'css', 'js', 'json', 'svg', 'png', 'jpg', 'jpeg', 'gif', 'webp',
  'ico', 'webmanifest', 'woff', 'woff2', 'ttf', 'otf', 'mp3', 'mp4', 'webm',
]);

// Never precache these (build outputs, dev config, machine data, huge non-runtime).
const DENY_EXACT = new Set([
  'sw.js', '404.html', '.htmlvalidate.json', 'tools/.htmlvalidate.json',
]);
const DENY_DIRS = [
  'docs/docs-files/',
  'tools/flove-apk/',
  'tools/flove-localhost.zip',
];

// The runnable site: home + apps + shared images (canonical) + tools + docs + whole wiki.
const tracked = execSync(
  'git ls-files index.html apps central/shared/media/images docs tools whole',
  { cwd: REPO, encoding: 'utf8' },
).split('\n').map(s => s.trim()).filter(Boolean);

// Entries are site-root-relative, resolved against the registration scope (/).
const files = tracked.filter(p => {
  const ext = p.split('.').pop().toLowerCase();
  if (!ALLOW.has(ext)) return false;
  if (DENY_EXACT.has(p)) return false;
  if (DENY_DIRS.some(d => p.startsWith(d))) return false;
  // Brand-study pages live beside the artwork but are dev docs, not runtime.
  if (p.startsWith('central/shared/media/images/') && ext === 'html') return false;
  // Ignore deletions not yet staged: git ls-files still lists them in the index.
  if (!existsSync(join(REPO, p))) return false;
  return true;
});

// Version hash from file contents → bumps whenever any cached file changes,
// which triggers the worker's activate cleanup + re-cache on next publish.
// Bump SW_REV when the worker's *logic* changes (not just cached files), so
// existing installs get a new cache name and drop the stale one on activate.
const SW_REV = 4;
const hash = createHash('sha256');
hash.update('rev' + SW_REV);
for (const p of files.sort()) hash.update(p).update(readFileSync(join(REPO, p)));
const VERSION = 'flove-' + hash.digest('hex').slice(0, 10);

// Scope-relative entries; BASE is resolved at runtime from the worker's own
// registration scope. The SAME generated sw.js works on flove.org (registered
// at /sw.js → scope /) and in the download package (also /sw.js → scope /).
// '' = the scope root, which aliases index.html.
const rel = ['', ...files];
const sw = `// sw.js — GENERATED by build-sw.mjs. Do not edit by hand.
// flove service worker: full-offline precache (${rel.length} entries).
const VERSION = ${JSON.stringify(VERSION)};
const BASE = self.registration.scope;
const PRECACHE = ${JSON.stringify(rel, null, 0)};

self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const cache = await caches.open(VERSION);
    // Cache each entry independently so one odd file can't abort the whole install.
    await Promise.allSettled(PRECACHE.map((p) => cache.add(BASE + p)));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  if (new URL(req.url).origin !== location.origin) return;

  const isPage = req.mode === 'navigate' ||
    (req.headers.get('accept') || '').includes('text/html');

  if (isPage) {
    // Pages: NETWORK-FIRST so an online visit always shows the latest content;
    // fall back to cache (then the gate) only when offline. Prevents the
    // "I published but still see the old page" service-worker trap.
    e.respondWith((async () => {
      try {
        const res = await fetch(req);
        if (res && res.ok && res.type === 'basic') {
          const cache = await caches.open(VERSION);
          cache.put(req, res.clone());
        }
        return res;
      } catch (err) {
        const cached = await caches.match(req, { ignoreSearch: true });
        if (cached) return cached;
        const gate = await caches.match(BASE + 'tools/start.html');
        if (gate) return gate;
        throw err;
      }
    })());
    return;
  }

  // Assets (css/js/img/…): CACHE-FIRST for speed; fill the cache on a miss.
  e.respondWith((async () => {
    const cached = await caches.match(req, { ignoreSearch: true });
    if (cached) return cached;
    try {
      const res = await fetch(req);
      if (res && res.ok && res.type === 'basic') {
        const cache = await caches.open(VERSION);
        cache.put(req, res.clone());
      }
      return res;
    } catch (err) {
      throw err;
    }
  })());
});
`;

// `--check` (used by tools/check-distro.sh) verifies without writing: exit 1 if
// the committed sw.js does not match what the tracked tree would generate.
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(join(ROOT, 'sw.js'), 'utf8'); } catch {}
  if (current === sw) {
    console.log(`sw.js up to date — ${VERSION}, ${rel.length} precache entries`);
  } else {
    console.error(`sw.js STALE — expected ${VERSION}, ${rel.length} precache entries; run it only in the heavy upgrady release`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(join(ROOT, 'sw.js'), sw);
  console.log(`sw.js written — ${VERSION}, ${rel.length} precache entries`);
}
